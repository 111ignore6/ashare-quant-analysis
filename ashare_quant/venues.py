"""行情源的品种口径差异 —— 同一字段在不同板块/不同源单位不一致时的唯一事实来源。

目前只有一条，但它是**已造成真实数据污染**的坑，所以单独成模块而不是散落在
两个调用点里各写一遍（realtime 快照与 tencent K 线都要用，而
``import ashare_quant.fetchers`` 会连带导入四个源模块、实测约 2.1s，
不适合被实时行情这种轻量路径依赖）。
"""

from __future__ import annotations


def volume_in_shares(code) -> bool:
    """该品种在腾讯行情里，成交量字段的单位是不是"股"（否则是"手"）。

    实测（2026-09-18，与新浪股数、本地 amount/收盘三方对撞）：

    - 科创板 **688/689 → 股**：688525 原始值 13,533,957 == 新浪股数；
      腾讯报价字段同理（40/40 样本吻合）。
    - 其他板块 **→ 手**：600000/000001/300750/920100 原始值 ×100 才等于股数
      （90/90 样本吻合）。

    所以"统一 ×100 换成股"对科创板会**放大 100 倍**：`tencent_fetcher._parse_kline`
    与实时快照都必须先问这个函数。历史污染见 AGENTS.md
    「科创板成交量单位」条（09-16/09-17 的 688 volume 即由此虚高 100 倍）。
    """
    return str(code).strip().lower()[-6:].startswith(("688", "689"))
